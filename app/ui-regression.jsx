import React from 'react';
import { createRoot } from 'react-dom/client';
import { flushSync } from 'react-dom';
import { View, Text } from 'react-native';
import { Card, Chip, Btn } from './src/ui';
import { Marketplace } from './src/marketplace';
import Login from './src/auth';
import { VendorCatalog } from './src/catalog';
import { PlanningJourney } from './src/journey';
import { TaskManager } from './src/planner';
import { SafeAreaProvider } from 'react-native-safe-area-context';

// Run in a DOM environment against the real web components. These checks catch
// wrapper/layout regressions and render failures, not browser pixel geometry.
window.runUiChecks = async () => {
  const container = document.createElement('div');
  document.body.appendChild(container);
  const root = createRoot(container);
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  flushSync(() => root.render(<Card onPress={() => {}} style={{ flex: 1 }}><Text>Task summary</Text></Card>));
  const button = container.querySelector('[role="button"]');
  check(button === container.firstElementChild, 'Clickable card must own its layout without an extra flex wrapper');
  check(getComputedStyle(button).flexGrow === '1', 'Card flex must be applied to the clickable root');
  check(getComputedStyle(button).paddingTop === '20px', 'Card content padding must be retained');
  flushSync(() => root.render(<View style={{ flexDirection: 'row', flexWrap: 'wrap' }}><Chip label="Photography" /><Chip label="Wedding details" /></View>));
  check(container.firstElementChild.children.length === 2, 'Filter row must contain two direct chips');
  check([...container.firstElementChild.children].every(el => el.getAttribute('role') === 'button'), 'Chips must own margins and dimensions in wrapping rows');
  flushSync(() => root.render(<Btn title="Explore wedding vendors" icon="search" onPress={() => {}} />));
  check(!!container.querySelector('svg path') && container.textContent.includes('Explore wedding vendors'), 'Button icon and text must render together');
  check(container.firstElementChild.getAttribute('role') === 'button', 'Button must own its margins directly');
  let closed = false;
  flushSync(() => root.render(<SafeAreaProvider initialMetrics={{ frame: { x: 0, y: 0, width: 390, height: 844 }, insets: { top: 47, bottom: 34, left: 0, right: 0 } }}><Login onDone={() => {}} onClose={() => { closed = true; }} lang="en" setLang={() => {}} /></SafeAreaProvider>));
  check([...container.querySelectorAll('[role="button"]')].some(el => el.textContent === 'Send code'), 'Login must render the send-code action');
  const notNow = [...container.querySelectorAll('[role="button"]')].find(el => el.textContent === 'Not now');
  check(!!notNow, 'Sign-in opened from the app must offer a way back');
  notNow.click();
  check(closed, 'Not now must close sign-in and return to the app');
  flushSync(() => root.render(<Marketplace openVendor={() => {}} />));
  await new Promise(resolve => setTimeout(resolve, 350));
  check(container.textContent.includes('Fixture photographer'), 'Directory must render a vendor from the API');
  check(!!container.querySelector('input'), 'Search field must render');
  check(container.querySelectorAll('svg').length >= 8, 'Service icons must render as SVG');
  const compare = [...container.querySelectorAll('[role="checkbox"]')].find(el => el.textContent === 'Compare');
  check(!!compare, 'Vendor card must expose comparison control');
  flushSync(() => compare.click());
  const showComparison = [...container.querySelectorAll('[role="button"]')].find(el => el.textContent === 'Show comparison');
  check(!!showComparison, 'Selecting a vendor must expose the comparison panel');
  flushSync(() => showComparison.click());
  check(container.textContent.includes('Compare vendors') && container.textContent.includes('View profile'), 'Comparison must render actual vendor details and a working profile action');
  flushSync(() => root.render(<VendorCatalog vendor={{ photos: [{ id: 1, url: 'https://portfolio.example/photo.jpg', caption: 'Ceremony coverage' }], packages: [{ id: 1, title: 'Ceremony package', description: 'Four hours of coverage', price_paise: 6500000 }] }} />));
  check(container.textContent.includes('Ceremony package') && container.textContent.includes('Four hours of coverage'), 'Customer profile must render the submitted package');
  check(!!container.querySelector('[aria-label="Ceremony coverage"]'), 'Portfolio image must retain its accessible caption');
  let imported = false; let handover = null;
  window.fetch = async (url, options = {}) => {
    const path = String(url);
    if (path.endsWith('/tasks/1') && options.method === 'PATCH') handover = JSON.parse(options.body);
    if (path.endsWith('/planner/guide/priorities') && options.method === 'POST') imported = true;
    const data = path.endsWith('/planner/guide') ? [{ key: 'priorities', title: 'Agree on your priorities together', phase: 'Foundations', due: '2026-10-12', already_added: imported, is_catch_up: true }] : path.endsWith('/tasks') ? [{ id: 1, title: 'Book venue', due: '2027-01-10', done: 0, owner: 'Meera', notes: 'East gate arrival', priority: 'high' }] : { ok: true };
    return { ok: true, json: async () => data };
  };
  flushSync(() => root.render(<TaskManager />));
  await new Promise(resolve => setTimeout(resolve, 30));
  check(container.textContent.includes('Book venue'), 'Planner must render the couple checklist');
  check(container.textContent.includes('tasks done'), 'Planner progress card must render');
  check(container.textContent.includes('Meera') && container.textContent.includes('East gate arrival'), 'Task must display the responsible person and handover notes');
  const action = label => [...container.querySelectorAll('[role="button"]')].find(el => el.textContent === label);
  flushSync(() => action('Unassigned').click());
  check(!container.textContent.includes('Book venue'), 'Unassigned filter must exclude assigned tasks');
  flushSync(() => action('High priority').click());
  check(container.textContent.includes('Book venue'), 'High priority filter must show urgent work');
  flushSync(() => action('Edit').click());
  check(container.textContent.includes('Responsible person (optional)') && container.textContent.includes('Handover notes (optional)'), 'Task editor must expose handover fields');
  check([...container.querySelectorAll('input,textarea')].some(el => el.value === 'Meera'), 'Task editor must retain saved ownership');
  flushSync(() => action('Normal').click());
  flushSync(() => action('Save task').click());
  await new Promise(resolve => setTimeout(resolve, 30));
  check(handover?.priority === 'normal' && handover.owner === 'Meera' && handover.notes === 'East gate arrival', 'Saving priorities must retain handover details');
  const ideas = [...container.querySelectorAll('[role="button"]')].find(el => el.textContent === 'Planning ideas');
  check(!!ideas, 'Planner must expose optional suggestions');
  flushSync(() => ideas.click());
  check(container.textContent.includes('Agree on your priorities together') && container.textContent.includes('Start now'), 'Date-aware suggestion must render');
  const addIdea = [...container.querySelectorAll('[role="button"]')].find(el => el.textContent === 'Add');
  check(!!addIdea, 'Suggestion must have an action');
  flushSync(() => addIdea.click());
  await new Promise(resolve => setTimeout(resolve, 30));
  check(imported, 'Adding a suggestion must call the guide API');
  const phase = { key: 'day', title: 'Run the wedding day', description: 'Hand over timings and contacts.', checks: [{ key: 'run-sheet', title: 'Run sheet started', done: true, detail: '3 timings recorded.', tab: 'run' }] };
  window.fetch = async () => ({ ok: true, json: async () => ({ done: 1, total: 1, phases: [phase] }) });
  let opened = '';
  flushSync(() => root.render(<PlanningJourney open={tab => { opened = tab; }} refreshKey={1} />));
  await new Promise(resolve => setTimeout(resolve, 30));
  check(container.textContent.includes('Run the wedding day'), 'Planning journey must render server checkpoints');
  const phaseButton = container.querySelector('[aria-expanded="false"]');
  flushSync(() => phaseButton.click());
  check(!!container.querySelector('[aria-expanded="true"]') && container.textContent.includes('3 timings recorded.'), 'Journey phase must expand to show saved planning work');
  const checkpoint = [...container.querySelectorAll('[role="button"]')].find(el => el.textContent.includes('Run sheet started'));
  flushSync(() => checkpoint.click());
  check(opened === 'run', 'Journey checkpoint must open its connected tool');
  flushSync(() => root.unmount());
  container.remove();
  return 'PASS: shared layout, SVG icons, browsing, comparison, portfolio, planning progress, checklist suggestions, task handovers and journey links';
};
